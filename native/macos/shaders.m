#import <Foundation/Foundation.h>
NSString *solar_shader_source(void) {
  return @"#include <metal_stdlib>\n"
         @"using namespace metal;\n"
         @"\n"
         @"struct Uniforms {\n"
         @"    float4x4 vp, model, normal;\n"
         @"    float4 sun, material, tint, eye;\n"
         @"    float4 spheres[32];\n"
         @"    float4 ringCenter[2], ringNormal[2], ringSize[2];\n"
         @"    float4 options;\n"
         @"};\n"
         @"struct SurfaceVertex {\n"
         @"    float4 position [[position]];\n"
         @"    float3 world, normal;\n"
         @"    float2 uv;\n"
         @"};\n"
         @"struct PointVertex {\n"
         @"    float4 position [[position]];\n"
         @"    float pointSize [[point_size]];\n"
         @"    float4 color;\n"
         @"};\n"
         @"struct LineVertex { float4 position, color; };\n"
         @"struct LineOutput { float4 position [[position]]; float4 color; };\n"
         @"\n"
         @"float3 encode(float3 linear) {\n"
         @"    float3 tone = linear / (1.0 + linear);\n"
         @"    return select(1.055 * pow(tone, float3(1.0 / 2.4)) - 0.055, "
         @"tone * 12.92, tone <= 0.0031308);\n"
         @"}\n"
         @"constexpr sampler mapSampler(coord::normalized, address::repeat, "
         @"filter::linear, mip_filter::linear);\n"
         @"constexpr sampler ringSampler(coord::normalized, "
         @"address::clamp_to_edge, filter::linear, mip_filter::linear);\n"
         @"\n"
         @"vertex SurfaceVertex sphere_vertex(uint vid [[vertex_id]], constant "
         @"Uniforms &u [[buffer(0)]]) {\n"
         @"    const uint corners[6] = {0, 1, 2, 2, 1, 3};\n"
         @"    uint corner = corners[vid % 6], quad = vid / 6;\n"
         @"    float2 uv = float2(float(quad % 96 + (corner & 1)) / 96.0,\n"
         @"                      float(quad / 96 + (corner >> 1)) / 48.0);\n"
         @"    float longitude = (uv.x - 0.5) * 2.0 * M_PI_F;\n"
         @"    float latitude = (0.5 - uv.y) * M_PI_F;\n"
         @"    float3 p = float3(cos(latitude) * cos(longitude), cos(latitude) "
         @"* sin(longitude), sin(latitude));\n"
         @"    float4 world = u.model * float4(p, 1);\n"
         @"    return {u.vp * world, world.xyz, normalize((u.normal * "
         @"float4(p, 0)).xyz), uv};\n"
         @"}\n"
         @"\n"
         @"float shadow(float3 p, float3 light, constant Uniforms &u, int "
         @"own,\n"
         @"             texture2d<float> saturnRing, texture2d<float> "
         @"uranusRing, bool testRings) {\n"
         @"    float distanceToSun = length(u.sun.xyz - p);\n"
         @"    for (int i = 0; i < int(u.options.x); ++i) {\n"
         @"        if (i == own || u.spheres[i].w <= 0) continue;\n"
         @"        float3 offset = p - u.spheres[i].xyz;\n"
         @"        float b = dot(offset, light), c = dot(offset, offset) - "
         @"u.spheres[i].w * u.spheres[i].w;\n"
         @"        float d = b * b - c;\n"
         @"        if (d > 0 && -b - sqrt(d) > 0.00001 && -b - sqrt(d) < "
         @"distanceToSun) return 0.035;\n"
         @"    }\n"
         @"    float transmission = 1.0;\n"
         @"    if (testRings) for (int i = 0; i < 2; ++i) {\n"
         @"        if (u.ringSize[i].z < 0.5) continue;\n"
         @"        float denominator = dot(light, u.ringNormal[i].xyz);\n"
         @"        if (abs(denominator) < 0.0001) continue;\n"
         @"        float t = dot(u.ringCenter[i].xyz - p, u.ringNormal[i].xyz) "
         @"/ denominator;\n"
         @"        if (t <= 0.00001 || t > distanceToSun) continue;\n"
         @"        float r = length(p + t * light - u.ringCenter[i].xyz);\n"
         @"        float inner = u.ringSize[i].x, outer = u.ringSize[i].y;\n"
         @"        if (r > inner && r < outer) {\n"
         @"            float2 uv = float2((r - inner) / (outer - inner), "
         @"0.5);\n"
         @"            float alpha = i == 0 ? saturnRing.sample(ringSampler, "
         @"uv).a : uranusRing.sample(ringSampler, uv).a;\n"
         @"            transmission *= 1.0 - alpha * 0.88;\n"
         @"        }\n"
         @"    }\n"
         @"    return transmission;\n"
         @"}\n"
         @"\n"
         @"fragment float4 sphere_fragment(SurfaceVertex v [[stage_in]], "
         @"constant Uniforms &u [[buffer(0)]],\n"
         @"                               texture2d<float> colorMap "
         @"[[texture(0)]],\n"
         @"                               texture2d<float> cloudMap "
         @"[[texture(1)]],\n"
         @"                               texture2d<float> normalMap "
         @"[[texture(2)]],\n"
         @"                               texture2d<float> saturnRing "
         @"[[texture(3)]],\n"
         @"                               texture2d<float> uranusRing "
         @"[[texture(4)]],\n"
         @"                               texture2d<float> nightMap "
         @"[[texture(5)]]) {\n"
         @"    float3 albedo = colorMap.sample(mapSampler, v.uv).rgb;\n"
         @"    if (u.tint.z > 0.5) albedo = albedo.rrr;\n"
         @"    if (u.material.x == 10) return float4(encode(albedo * 3.6), "
         @"1);\n"
         @"    float3 n = normalize(v.normal);\n"
         @"    if (u.material.x == 399 || u.material.x == 301) {\n"
         @"        float longitude = (v.uv.x - 0.5) * 2.0 * M_PI_F;\n"
         @"        float3 tangent = normalize((u.normal * "
         @"float4(-sin(longitude), cos(longitude), 0, 0)).xyz);\n"
         @"        float3 bitangent = normalize(cross(n, tangent));\n"
         @"        float3 mapped = normalMap.sample(mapSampler, v.uv).xyz * "
         @"2.0 - 1.0;\n"
         @"        mapped.xy *= u.material.x == 301 ? 0.6 : 0.35;\n"
         @"        n = normalize(tangent * mapped.x + bitangent * mapped.y + n "
         @"* mapped.z);\n"
         @"    }\n"
         @"    float cloud = 0;\n"
         @"    if (u.material.x == 399) {\n"
         @"        float4 c = cloudMap.sample(mapSampler, v.uv);\n"
         @"        cloud = (u.options.w > 0.5 ? c.g : c.a) * c.r;\n"
         @"        albedo = mix(albedo, float3(0.86), cloud * 0.9);\n"
         @"    }\n"
         @"    float3 l = normalize(u.sun.xyz - v.world), eye = "
         @"normalize(-v.world);\n"
         @"    float nl = max(dot(n, l), 0.0), nv = max(dot(n, eye), 0.001);\n"
         @"    float3 h = normalize(l + eye);\n"
         @"    float roughness = u.material.y;\n"
         @"    if (u.material.x == 399 && albedo.b > albedo.r * 1.3 && cloud < "
         @"0.15) roughness = 0.22;\n"
         @"    float a2 = pow(roughness, 4.0), nh = max(dot(n, h), 0.0);\n"
         @"    float d = a2 / max(M_PI_F * pow(nh * nh * (a2 - 1.0) + 1.0, "
         @"2.0), 0.00001);\n"
         @"    float k = pow(roughness + 1.0, 2.0) / 8.0;\n"
         @"    float g = nv / (nv * (1.0 - k) + k) * nl / (nl * (1.0 - k) + "
         @"k);\n"
         @"    float f = 0.04 + 0.96 * pow(1.0 - max(dot(h, eye), 0.0), 5.0);\n"
         @"    float specular = d * g * f / max(4.0 * nl * nv, 0.001);\n"
         @"    float visibility = shadow(v.world + n * 0.000002, l, u, "
         @"int(u.material.z), saturnRing, uranusRing, true);\n"
         @"    float illumination = 1.45 / pow(max(length(u.sun.xyz - "
         @"v.world), 0.4), 0.09);\n"
         @"    float3 linear = albedo * 0.004 + (albedo * (1.0 - f) + "
         @"specular) * nl * visibility * illumination;\n"
         @"    if (u.material.x == 399) {\n"
         @"        linear += nightMap.sample(mapSampler, v.uv).rgb * pow(1.0 - "
         @"nl, 5.0) * 0.28;\n"
         @"        linear += float3(0.07, 0.22, 0.5) * pow(1.0 - nv, 3.0) * "
         @"smoothstep(-0.2, 0.6, dot(n,l)) * 0.7;\n"
         @"    }\n"
         @"    if (u.material.w > 0.5) linear += float3(0.12, 0.25, 0.35) * "
         @"pow(1.0 - nv, 8.0);\n"
         @"    return float4(encode(linear), 1);\n"
         @"}\n"
         @"\n"
         @"vertex SurfaceVertex ring_vertex(uint vid [[vertex_id]], constant "
         @"Uniforms &u [[buffer(0)]]) {\n"
         @"    const uint corners[6] = {0,1,2,2,1,3};\n"
         @"    uint c=corners[vid%6];\n"
         @"    float angle=(float(vid/6+(c&1))/384.0)*2*M_PI_F;\n"
         @"    float t=float(c>>1), radius=mix(u.tint.x,u.tint.y,t);\n"
         @"    float4 "
         @"world=u.model*float4(cos(angle)*radius,sin(angle)*radius,0,1);\n"
         @"    return "
         @"{u.vp*world,world.xyz,normalize((u.normal*float4(0,0,1,0)).xyz),"
         @"float2(t,0.5)};\n"
         @"}\n"
         @"fragment float4 ring_fragment(SurfaceVertex v [[stage_in]], "
         @"constant Uniforms &u [[buffer(0)]],\n"
         @"                             texture2d<float> map [[texture(0)]], "
         @"texture2d<float> saturnRing [[texture(3)]],\n"
         @"                             texture2d<float> uranusRing "
         @"[[texture(4)]]) {\n"
         @"    float4 sample=map.sample(ringSampler,v.uv);\n"
         @"    float3 l=normalize(u.sun.xyz-v.world);\n"
         @"    float "
         @"visibility=shadow(v.world,l,u,-1,saturnRing,uranusRing,false);\n"
         @"    float nl=abs(dot(normalize(v.normal),l));\n"
         @"    return "
         @"float4(encode(sample.rgb*(0.04+(0.3+nl)*visibility)),sample.a*0.9);"
         @"\n"
         @"}\n"
         @"\n"
         @"vertex LineOutput line_vertex(uint vid [[vertex_id]], const device "
         @"LineVertex *vertices [[buffer(1)]], constant Uniforms &u "
         @"[[buffer(0)]]) {\n"
         @"    return {u.vp*vertices[vid].position,vertices[vid].color};\n"
         @"}\n"
         @"fragment float4 line_fragment(LineOutput v [[stage_in]]) { return "
         @"v.color; }\n"
         @"\n"
         @"float hash(uint n) { "
         @"n=(n^61u)^(n>>16);n*=9u;n^=n>>4;n*=0x27d4eb2du;n^=n>>15;return "
         @"float(n)/4294967296.0; }\n"
         @"vertex PointVertex particle_vertex(uint vid [[vertex_id]], constant "
         @"Uniforms &u [[buffer(0)]]) {\n"
         @"    float3 p;float size;float4 color;\n"
         @"    if (u.tint.w < 0.5) {\n"
         @"        float z=hash(vid*5+1)*2-1,angle=hash(vid*5+2)*2*M_PI_F;\n"
         @"        float r=sqrt(1-z*z);\n"
         @"        p=float3(r*cos(angle),r*sin(angle),z)*900;\n"
         @"        size=1.0+hash(vid*5+3)*1.8;\n"
         @"        color=float4(0.52,0.65,0.85,0.15+hash(vid*5+4)*0.65);\n"
         @"    } else {\n"
         @"        float a=2.12+hash(vid*7+1)*1.18,e=hash(vid*7+2)*0.13;\n"
         @"        float "
         @"m=hash(vid*7+3)*2*M_PI_F+u.options.y*2*M_PI_F/(365.25*pow(a,1.5));\n"
         @"        m=fmod(m,2*M_PI_F);float anomaly=m;\n"
         @"        for(int i=0;i<5;i++) "
         @"anomaly-=(anomaly-e*sin(anomaly)-m)/(1-e*cos(anomaly));\n"
         @"        float3 "
         @"local=float3(a*(cos(anomaly)-e),a*sqrt(1-e*e)*sin(anomaly),0);\n"
         @"        float "
         @"node=hash(vid*7+4)*2*M_PI_F,inclination=(hash(vid*7+5)-0.5)*0.18;\n"
         @"        "
         @"local.yz=float2(local.y*cos(inclination),local.y*sin(inclination));"
         @"\n"
         @"        "
         @"p=float3(local.x*cos(node)-local.y*sin(node),local.x*sin(node)+"
         @"local.y*cos(node),local.z)-u.eye.xyz;\n"
         @"        size=1.3+hash(vid*7+6)*1.1;\n"
         @"        color=float4(0.56,0.50,0.40,0.32);\n"
         @"    }\n"
         @"    return {u.vp*float4(p,1),size,color};\n"
         @"}\n"
         @"fragment float4 particle_fragment(PointVertex v [[stage_in]],float2 "
         @"point [[point_coord]]) {\n"
         @"    float r=length(point-0.5)*2;\n"
         @"    if(r>1) discard_fragment();\n"
         @"    return float4(v.color.rgb,v.color.a*(1-r*r));\n"
         @"}\n"
         @"\n"
         @"vertex PointVertex glow_vertex(uint vid [[vertex_id]],constant "
         @"Uniforms &u [[buffer(0)]]) {\n"
         @"    (void)vid;\n"
         @"    return "
         @"{u.vp*float4(u.sun.xyz,1),u.tint.x,float4(1.0,0.7,0.35,0.26)};\n"
         @"}\n"
         @"fragment float4 glow_fragment(PointVertex v [[stage_in]],float2 "
         @"point [[point_coord]]) {\n"
         @"    float r=length(point-0.5)*2;\n"
         @"    float alpha=exp(-r*r*6.0)*smoothstep(1.0,0.6,r);\n"
         @"    return float4(v.color.rgb,alpha*v.color.a);\n"
         @"}\n";
}
